import os
import sys
import csv
import importlib.util
from codecarbon import EmissionsTracker

# Constants
LLMs = ["chatgpt", "claude", "gemini"]

PROBLEM = "sorting"

for llm in LLMs:
    # Dynamic Loader Helper
    def load_algorithm(llm, problem_category, algorithm_name):
        """
        Dynamically loads the python file generated by a specific llm and retrieves the function.
        E.g. load_algorithm("claude", "sorting", "bubble_sort") loads:
        generated_code/claude/sorting/bubble_sort.py -> function bubble_sort()
        """
        module_path = os.path.abspath(os.path.join(
            os.path.dirname(__file__), 
            "..", 
            "generated_code", 
            llm, 
            problem_category, 
            f"{algorithm_name}.py"
        ))
        
        if not os.path.exists(module_path):
            raise FileNotFoundError(f"Generated code not found at: {module_path}")
            
        spec = importlib.util.spec_from_file_location(algorithm_name, module_path)
        module = importlib.util.module_from_spec(spec)
        sys.modules[algorithm_name] = module
        spec.loader.exec_module(module)
        
        func = getattr(module, algorithm_name, None)
        if func is None:
            raise AttributeError(f"Function `{algorithm_name}` not found in module.")
        return func

    # Experimental scales & target algorithms
    scales = [1000, 10000, 100000]
    algorithms = ["bubble_sort", "merge_sort", "heap_sort", "radix_sort", "counting_sort"]

    for scale in scales:
        # Loading data file generated by generate_data.py
        unordered_numbers = []
        csv_path = os.path.join("data", PROBLEM, f"unordered_numbers_{scale}.csv")
        
        try:
            with open(csv_path, "r") as file:
                reader = csv.reader(file)
                next(reader)  # Skip the header ("number")

                for row in reader:
                    unordered_numbers.append(int(row[0]))
        except FileNotFoundError:
            print(f"[-] Data file not found: {csv_path}. Please run generate_data.py first.")
            continue

        # Running a single trial (1, 2) matches range(1, 2) in your original script
        for i in range(1, 2):
            for algo in algorithms:
                try:
                    # Load function dynamically from generated_code/{llm}/{PROBLEM}/{algo}.py
                    function = load_algorithm(llm, PROBLEM, algo)
                except Exception as e:
                    # Log load failures (e.g. if the llm file is not generated yet) and skip
                    print(f"[-] Skipping {algo}: {e}")
                    continue

                output_dir = f"results/{llm}/{PROBLEM}/{algo}/"
                os.makedirs(output_dir, exist_ok=True)
                
                with EmissionsTracker(project_name="paper", output_file=f"numbers_{scale}.csv", output_dir=output_dir) as tracker:
                    ordered_numbers = function(unordered_numbers)

print("[+] Benchmarking run completed.")
